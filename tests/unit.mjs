import assert from 'node:assert/strict';
import * as T from '../src/time.js';
import { normalizeBaseUrl, splitOrderBy, jqlString } from '../src/jira.js';
const M=60000;
assert.equal(T.toJiraTime(0),'0m'); assert.equal(T.toJiraTime(90*M),'1h 30m'); assert.equal(T.toJiraTime(60*M),'1h');
assert.equal(T.toJiraTime(9*60*M),'1d 1h'); assert.equal(T.toJiraTime(9*60*M,7.5),'1d 1h 30m');
assert.equal(T.parseJiraTime('1h 30m'),90*M); assert.equal(T.parseJiraTime('1.5h'),90*M); assert.equal(T.parseJiraTime('1,5h'),90*M);
assert.equal(T.parseJiraTime('1:15'),75*M); assert.equal(T.parseJiraTime('45'),45*M); assert.equal(T.parseJiraTime('1d'),480*M);
assert.equal(T.parseJiraTime('1w'),2400*M); assert.equal(T.parseJiraTime('2H5M'),125*M); assert.equal(T.parseJiraTime('abc'),null);
assert.equal(T.parseJiraTime('1h x'),null); assert.equal(T.parseJiraTime(''),null);
assert.equal(T.parseTimeEdit('+15m',60*M),75*M); assert.equal(T.parseTimeEdit('-2h',60*M),0); assert.equal(T.parseTimeEdit('2h',5),120*M);
assert.equal(T.clock(3723000),'1:02:03'); assert.equal(T.ceilMinute(61000),120000);
assert.match(T.toJiraDate(new Date()), /^\d{4}-\d\d-\d\dT\d\d:\d\d:\d\d\.\d{3}[+-]\d{4}$/);
assert.equal(T.parseKey('https://x.atlassian.net/browse/abc-123?foo'),'ABC-123');
assert.equal(normalizeBaseUrl('acme.atlassian.net/browse/X-1'),'https://acme.atlassian.net');
assert.equal(normalizeBaseUrl('https://acme.atlassian.net/jira/software/projects/X/boards/1'),'https://acme.atlassian.net');
assert.equal(normalizeBaseUrl('https://corp.local/jira/'),'https://corp.local/jira');
assert.deepEqual(splitOrderBy('assignee = currentUser() ORDER BY updated DESC'),{where:'assignee = currentUser()',order:'ORDER BY updated DESC'});
assert.deepEqual(splitOrderBy('ORDER BY x'),{where:'',order:'ORDER BY x'});
assert.equal(jqlString('a "b"'),'"a \\"b\\""');
console.log('all unit tests passed');
